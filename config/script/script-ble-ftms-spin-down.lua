-- linkassist:type = script

return {
  version = 1,
  name = "ble-ftms-spin-down",
  description = "Start FTMS spin-down calibration over BLE. The script requests control, subscribes to the FTMS control point and status characteristics, starts spin-down, and waits for the control-point acknowledgements.",
  helpers = {
    bench = { luaPath = "../script-helper/script-helper-test-bench.lua" },
  },
  defaults = {
    stopOnFailure = true,
    timeoutMs = 8000,
    dataFormat = "hex",
    logLimit = 500,
  },
  variables = {
    deviceId = "",
    channelName = "Active FTMS BLE Channel",
    ftmsServiceUuid = "00001826-0000-1000-8000-00805f9b34fb",
    controlPointCharUuid = "00002ad9-0000-1000-8000-00805f9b34fb",
    statusCharUuid = "00002ada-0000-1000-8000-00805f9b34fb",
    indoorBikeDataCharUuid = "00002ad2-0000-1000-8000-00805f9b34fb",
    featureCharUuid = "00002acc-0000-1000-8000-00805f9b34fb",
    requestControlHex = "00",
    spinDownStartHex = "13 01",
    targetSpeedWaitMs = 30000,
    resultWaitMs = 90000,
  },
  setup = {
    {
      id = "open-ftms-control-point",
      action = "open",
      channel = "ftmsControl",
      channelType = "ble",
      name = "${channelName}",
      params = {
        deviceId = "${deviceId}",
        useActiveChannel = true,
        serviceUuid = "${ftmsServiceUuid}",
        charUuid = "${controlPointCharUuid}",
        subscribe = true,
      },
    },
    {
      id = "open-ftms-status",
      action = "open",
      channel = "ftmsStatus",
      channelType = "ble",
      name = "${channelName}",
      params = {
        deviceId = "${deviceId}",
        useActiveChannel = true,
        serviceUuid = "${ftmsServiceUuid}",
        charUuid = "${statusCharUuid}",
        subscribe = true,
      },
    },
    {
      id = "open-ftms-bike-data",
      action = "open",
      channel = "ftmsBikeData",
      channelType = "ble",
      name = "${channelName}",
      params = {
        deviceId = "${deviceId}",
        useActiveChannel = true,
        serviceUuid = "${ftmsServiceUuid}",
        charUuid = "${indoorBikeDataCharUuid}",
        subscribe = true,
      },
    },
    {
      id = "open-ftms-feature",
      action = "open",
      channel = "ftmsFeature",
      channelType = "ble",
      name = "${channelName}",
      params = {
        deviceId = "${deviceId}",
        useActiveChannel = true,
        serviceUuid = "${ftmsServiceUuid}",
        charUuid = "${featureCharUuid}",
        subscribe = false,
      },
    },
  },
  steps = {
    {
      id = "read-ftms-feature",
      action = "read",
      channel = "ftmsFeature",
      saveAs = "ftmsFeature",
    },
    {
      id = "log-ftms-feature",
      action = "log",
      message = "FTMS feature: ${ftmsFeature.hex}",
    },
    {
      id = "request-control",
      action = "request",
      channel = "ftmsControl",
      send = {
        format = "hex",
        value = "${requestControlHex}",
      },
      expect = {
        format = "hex",
        startsWith = "80 00 01",
      },
      saveAs = "requestControlResponse",
    },
    {
      id = "log-request-control-response",
      action = "log",
      message = "FTMS request control response: ${requestControlResponse.hex}",
    },
    {
      id = "start-spin-down",
      action = "request",
      channel = "ftmsControl",
      send = {
        format = "hex",
        value = "${spinDownStartHex}",
      },
      expect = {
        format = "hex",
        startsWith = "80 13 01",
      },
      saveAs = "spinDownControlResponse",
      timeoutMs = 10000,
    },
    {
      id = "log-spin-down-start-response",
      action = "log",
      message = "FTMS spin-down accepted: ${spinDownControlResponse.hex}",
    },
    {
      id = "decode-spin-down-target-range",
      action = "luaHelper",
      helper = "bench",
      func = "spinDownTarget",
      args = { bytes = { ["$ref"] = "spinDownControlResponse.bytes" } },
      saveAs = "spinDownTarget",
    },
    {
      id = "assert-spin-down-target-range",
      action = "assert",
      left = "${spinDownTarget.available}",
      operator = "=",
      right = "true",
    },
    {
      id = "log-spin-down-target-speed",
      action = "log",
      message = "FTMS spin-down target speed: ${spinDownTarget.label}. Reach the target range within 30 seconds.",
    },
    {
      id = "wait-target-speed",
      action = "wait",
      channel = "ftmsBikeData",
      expect = {
        luaHelper = {
          helper = "bench",
          func = "indoorBikeSpeedInTarget",
          args = {
            bytes = { ["$ref"] = "packet.bytes" },
            target = { ["$ref"] = "spinDownTarget" },
          },
          resultPath = "matched",
          equals = true,
        },
      },
      timeoutMs = "${targetSpeedWaitMs}",
      saveAs = "targetSpeedPacket",
    },
    {
      id = "decode-target-speed",
      action = "luaHelper",
      helper = "bench",
      func = "indoorBikeSpeed",
      args = { bytes = { ["$ref"] = "targetSpeedPacket.bytes" } },
      saveAs = "targetSpeed",
    },
    {
      id = "log-stop-pedaling-prompt",
      action = "log",
      message = "Reached target speed ${targetSpeed.label} (target ${spinDownTarget.label}). Stop pedaling now.",
    },
    {
      id = "wait-spin-down-result",
      action = "wait",
      channel = "ftmsStatus",
      expect = {
        luaHelper = {
          helper = "bench",
          func = "spinDownResultReady",
          args = { bytes = { ["$ref"] = "packet.bytes" } },
          resultPath = "matched",
          equals = true,
        },
      },
      timeoutMs = "${resultWaitMs}",
      saveAs = "spinDownResultStatus",
    },
    {
      id = "decode-spin-down-result",
      action = "luaHelper",
      helper = "bench",
      func = "spinDownStatus",
      args = { bytes = { ["$ref"] = "spinDownResultStatus.bytes" } },
      saveAs = "spinDownResult",
    },
    {
      id = "log-spin-down-result",
      action = "log",
      message = "FTMS spin-down result: ${spinDownResult.label} (${spinDownResultStatus.hex})",
    },
    {
      id = "assert-spin-down-success",
      action = "assert",
      left = "${spinDownResult.code}",
      operator = "=",
      right = "2",
    },
  },
  teardown = {
    {
      id = "close-ftms-bike-data",
      action = "close",
      channel = "ftmsBikeData",
      display = "hidden",
    },
    {
      id = "close-ftms-feature",
      action = "close",
      channel = "ftmsFeature",
      display = "hidden",
    },
    {
      id = "close-ftms-status",
      action = "close",
      channel = "ftmsStatus",
      display = "hidden",
    },
    {
      id = "close-ftms-control-point",
      action = "close",
      channel = "ftmsControl",
      display = "hidden",
    },
  },
}
