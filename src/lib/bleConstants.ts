const STANDARD_UUID_PATTERN = /^[0-9a-f]{4}$/i;
const STANDARD_BASE_UUID_PATTERN = new RegExp(`^0000([0-9a-f]{4})\-0000-1000-8000-00805f9b34fb$`, 'i');

function normalizeUuid(uuid: string): string {
  return uuid.trim().toLowerCase();
}

function shortUuidToBaseUuid(shortUuid: string): string {
  return `0000${shortUuid.toLowerCase()}${BLE_BASE_UUID_SUFFIX}`;
}

export function extractShortUuid(uuid: string): string | undefined {
  const normalized = normalizeUuid(uuid);
  if (STANDARD_UUID_PATTERN.test(normalized)) {
    return normalized;
  }

  const standardMatch = normalized.match(STANDARD_BASE_UUID_PATTERN);
  if (standardMatch) {
    return standardMatch[1];
  }

  return undefined;
}

export function getAppearanceName(value: number): string {
  const exact = APPEARANCE_MAP_RECORD[value];
  if (exact) {
    return exact.name;
  }

  const generic = APPEARANCE_MAP_RECORD[(value >> 6) << 6];
  return generic?.name ?? APPEARANCE_MAP_RECORD[0x0000].name;
}

export function getAppearanceCategory(value: number): string {
  const exact = APPEARANCE_MAP_RECORD[value];
  if (exact) {
    return exact.category;
  }

  const majorCategory = value >> 6;
  return APPEARANCE_CATEGORY_BY_MAJOR_RECORD[majorCategory] ?? 'unknown';
}

export function getServiceName(uuid: string): string | undefined {
  const normalized = normalizeUuid(uuid);
  const shortUuid = extractShortUuid(normalized);
  if (shortUuid) {
    return GATT_SERVICE_NAMES_RECORD[shortUuid]
      ?? WELL_KNOWN_VENDOR_UUIDS_RECORD[shortUuidToBaseUuid(shortUuid)]
      ?? WELL_KNOWN_VENDOR_UUIDS_RECORD[shortUuid];
  }

  return WELL_KNOWN_VENDOR_UUIDS_RECORD[normalized];
}

