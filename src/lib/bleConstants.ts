export function inferAppearanceFromServices(serviceUuids: string[]): number | undefined {
  const normalizedShortUuids = serviceUuids
    .map((uuid) => extractShortUuid(uuid) ?? normalizeUuid(uuid))
    .map((uuid) => uuid.toLowerCase());

  for (const [serviceUuid, appearance] of Object.entries(SERVICE_TO_APPEARANCE_CATEGORY)) {
    if (normalizedShortUuids.includes(serviceUuid)) {
      return appearance;
    }
  }

  return undefined;
}

